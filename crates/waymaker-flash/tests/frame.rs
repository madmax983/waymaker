#[test]
fn padding_is_written_erased_and_never_read_back() {
    // "Records padded to the device's program alignment, with stale tail bytes never
    // interpreted." Padding is written as `0xFF` because that is what an erased NOR cell
    // already holds, so programming it changes no bits; and the decoder's reported length
    // stops at the frame, so a reader never treats the pad as data.
    let record = RecordRef::EffectCompleted {
        seq: EffectSeq(1),
        result: b"five!",
    };
    let align = ProgramAlign::new(16).expect("a non-zero alignment");
    let mut page = [0_u8; SCRATCH];
    let written = frame::encode(&record, align, &mut page).expect("room");

    let frame_len = FRAME_OVERHEAD_BYTES + 5;
    let body = frame::body_len(&record, align).expect("this record encodes");
    assert_eq!(body, 32, "21 bytes of frame padded up to 16-byte units");
    assert_eq!(
        written, 48,
        "and a sixteen-byte commit seal after the padding"
    );
    assert!(
        page[frame_len..body]
            .iter()
            .all(|byte| *byte == ERASED_BYTE),
        "the pad between the frame and its seal is erased"
    );

    let decoded = frame::decode(&page[..written]).expect("a valid frame");
    assert_eq!(decoded.frame_len, frame_len);
    assert_eq!(decoded.decoded, Decoded::Record(record));

    // Stale bytes where the pad is: still the same record, because nothing reads them.
    let mut stale = page;
    for slot in stale.iter_mut().take(body).skip(frame_len) {
        *slot = 0x5A;
    }
    assert_eq!(decoded_record(&stale[..body]), Some(record));
}

#[test]
fn an_alignment_must_be_a_power_of_two() {
    // Zero is not "no padding", it is a division by zero, and it is rejected once at
    // construction rather than guarded at every use. Everything else the constructor turns
    // away is turned away for a firmware reason: rounding up by `%` on a runtime `u16`
    // links `compiler_builtins`' software division on a chip with no divide instruction —
    // around 430 B of an 8 KiB budget — and leaves a live divide-by-zero panic branch.
    // A power of two rounds up by mask, in three instructions that cannot trap.
    assert!(ProgramAlign::new(0).is_none(), "zero is a division by zero");
    for refused in [3_u16, 5, 6, 7, 13, 255, 1_000, 65_535] {
        assert!(
            ProgramAlign::new(refused).is_none(),
            "{refused} is not a power of two"
        );
    }
    for accepted in ALIGNMENTS {
        assert_eq!(
            ProgramAlign::new(accepted).map(ProgramAlign::get),
            Some(accepted)
        );
    }
    assert_eq!(ProgramAlign::BYTE.get(), 1);
    assert_eq!(
        ProgramAlign::new(32_768).map(ProgramAlign::get),
        Some(32_768),
        "the largest power of two a u16 holds"
    );
    assert_eq!(ProgramAlign::new(4_096).map(ProgramAlign::get), Some(4_096));
}

#[test]
fn rounding_up_lands_on_the_next_program_unit() {
    let align = ProgramAlign::new(8).expect("a power of two");
    assert_eq!(align.round_up(0), Some(0));
    assert_eq!(align.round_up(1), Some(8));
    assert_eq!(align.round_up(7), Some(8));
    assert_eq!(align.round_up(8), Some(8));
    assert_eq!(align.round_up(9), Some(16));
    // A length that cannot be rounded up without wrapping has no answer, rather than an
    // answer that is smaller than the input — which would be a writer told it had room it
    // does not have.
    assert_eq!(align.round_up(usize::MAX), None);
    assert_eq!(ProgramAlign::BYTE.round_up(usize::MAX), Some(usize::MAX));

    // The three postconditions, over every alignment and a spread of lengths, rather than
    // over the handful of pairs written out above.
    for granularity in ALIGNMENTS {
        let align = ProgramAlign::new(granularity).expect("a power of two");
        let unit = usize::from(granularity);
        for len in [0_usize, 1, 15, 16, 17, 4_095, 65_551, 100_000] {
            let padded = align.round_up(len).expect("no overflow at these lengths");
            assert_eq!(padded % unit, 0, "{granularity}/{len}: not a whole unit");
            assert!(padded >= len, "{granularity}/{len}: shorter than its input");
            assert!(padded < len + unit, "{granularity}/{len}: padded too far");
        }
    }
}

#[test]
fn a_scan_walks_padded_frames_and_stops_at_the_erased_tail() {
    // What recovery does: walk the journal in order until the bytes stop being records.
    // An erased tail is the ordinary end of history rather than damage, so it ends the
    // scan without an error.
    let align = ProgramAlign::new(16).expect("a non-zero alignment");
    let records = [
        RecordRef::RunStarted {
            workflow_kind: 4,
            workflow_version: 1,
            input: b"start",
        },
        RecordRef::EffectScheduled {
            seq: EffectSeq(0),
            kind: ActivityKind(1),
            input_len: 3,
            input_crc: 0x1234_5678,
        },
        RecordRef::EffectCompleted {
            seq: EffectSeq(0),
            result: b"done",
        },
        RecordRef::RunCompleted { result: &[] },
    ];

    let mut journal = [ERASED_BYTE; SCRATCH];
    let mut at = 0;
    for record in records {
        let written =
            frame::encode(&record, align, &mut journal[at..]).expect("room in the journal");
        at += written;
    }

    let mut scan = Scan::new(&journal, align);
    let walked: Vec<Result<RecordRef<'_>, DecodeError>> = scan.by_ref().collect();
    assert_eq!(walked, records.map(Ok).to_vec());
    assert_eq!(
        scan.offset(),
        at,
        "the scan stops where the next append goes"
    );
    // Fused: a scan that ended is a scan that stays ended, so a caller that keeps asking
    // does not restart the journal.
    assert!(scan.next().is_none());
    assert!(scan.next().is_none());
}

#[test]
fn a_scan_stops_at_the_first_damaged_frame_and_reports_where() {
    // §09: "Recovery stops at the first unsealed, malformed, out-of-sequence, or
    // integrity-failed frame." The prefix before the damage is history; nothing after it
    // is, even if it happens to decode.
    let align = ProgramAlign::BYTE;
    let mut journal = [ERASED_BYTE; SCRATCH];

    let first = frame::encode(
        &RecordRef::RunStarted {
            workflow_kind: 1,
            workflow_version: 1,
            input: b"a",
        },
        align,
        &mut journal,
    )
    .expect("room");
    let second = frame::encode(
        &RecordRef::EffectCompleted {
            seq: EffectSeq(0),
            result: b"b",
        },
        align,
        &mut journal[first..],
    )
    .expect("room");
    let third_at = first + second;
    frame::encode(
        &RecordRef::RunCompleted { result: b"c" },
        align,
        &mut journal[third_at..],
    )
    .expect("room");

    // A bit flip in the middle frame's payload.
    journal[first + HEADER_BYTES] ^= 0x01;

    let mut scan = Scan::new(&journal, align);
    assert_eq!(
        scan.next(),
        Some(Ok(RecordRef::RunStarted {
            workflow_kind: 1,
            workflow_version: 1,
            input: b"a",
        }))
    );
    assert_eq!(scan.next(), Some(Err(DecodeError::IntegrityFailed)));
    // The third frame is intact and is still not history: everything after the first
    // failure is outside the committed prefix.
    assert!(scan.next().is_none());
    assert_eq!(
        scan.offset(),
        first,
        "the append point is the start of the frame that failed"
    );
}

