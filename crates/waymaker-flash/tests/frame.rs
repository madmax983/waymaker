#[test]
fn a_scan_always_terminates_and_advances() {
    // The scanner is the one loop in this crate, so it is the one place a malformed journal
    // could hang rather than fail.
    //
    // Random bytes alone cannot test that: they never carry the magic, so the scan stops on
    // its first step every time and a step counter never exceeds one. Half the journals here
    // are therefore built from real frames and then damaged, which is what produces scans of
    // several steps — and the test asserts it saw them, so a generator that stopped
    // producing them is a failure rather than a quiet return to testing nothing.
    let mut rng = Rng::new(0x5EED_0004);
    let mut journal = [0_u8; 512];
    let mut deepest = 0;

    for iteration in 0..2_000 {
        let align = ProgramAlign::new(ALIGNMENTS[rng.below(ALIGNMENTS.len())])
            .expect("a non-zero alignment");

        if iteration % 2 == 0 {
            for slot in &mut journal {
                *slot = rng.next_u8();
            }
        } else {
            // A run of real frames, then a few random bytes somewhere in it.
            journal.fill(ERASED_BYTE);
            let mut at = 0;
            for index in 0..6_u32 {
                let record = RecordRef::EffectCompleted {
                    seq: EffectSeq(index),
                    result: b"payload",
                };
                match frame::encode(&record, align, &mut journal[at..]) {
                    Ok(written) => at += written,
                    Err(_) => break,
                }
            }
            for _ in 0..rng.below(4) {
                let at = rng.below(journal.len());
                journal[at] = rng.next_u8();
            }
        }

        let mut scan = Scan::new(&journal, align);
        let mut steps = 0;
        while scan.next().is_some() {
            steps += 1;
            assert!(
                steps <= journal.len() / FRAME_OVERHEAD_BYTES + 1,
                "iteration {iteration}: the scan did not advance"
            );
        }
        deepest = deepest.max(steps);
        assert!(scan.offset() <= journal.len(), "iteration {iteration}");
    }

    assert!(
        deepest > 1,
        "no journal took more than one step, so nothing here tested advancing"
    );
}

#[test]
fn a_frame_whose_padding_does_not_fit_the_journal_is_a_truncation() {
    // `encode` reserves the whole padded length before it writes a byte, so a journal that
    // ends after a frame's checksum but before its padding is a journal shorter than the
    // frame it appears to hold. Accepting the record would advance to an offset that is not
    // on a program boundary — not a place anything may be written — so the scan fails closed
    // and `Scan::offset`'s "always a whole number of program units" stays true.
    let align = ProgramAlign::new(16).expect("a power of two");
    let mut page = [0_u8; SCRATCH];
    let record = RecordRef::RunCompleted { result: b"abc" };
    let written = frame::encode(&record, align, &mut page).expect("room");
    let frame_len = FRAME_OVERHEAD_BYTES + 3;
    assert!(
        written > frame_len,
        "the record must be padded for this to test anything"
    );

    // Every cut between the end of the frame and the end of its padding.
    for cut in frame_len..written {
        let mut scan = Scan::new(&page[..cut], align);
        assert_eq!(
            scan.next(),
            Some(Err(DecodeError::Truncated)),
            "a journal cut to {cut} bytes holds a frame whose padding is not there"
        );
        assert!(scan.next().is_none());
        assert_eq!(
            scan.offset(),
            0,
            "the append point is the frame's own start"
        );
    }

    // And the whole padded frame walks, so the refusal above is about the missing padding
    // rather than about the frame.
    let mut whole = Scan::new(&page[..written], align);
    assert_eq!(whole.next(), Some(Ok(record)));
    assert_eq!(whole.offset(), written);
    assert_eq!(whole.offset() % usize::from(align.get()), 0);
}

#[test]
fn a_torn_short_header_at_the_end_of_a_journal_is_not_a_clean_end() {
    // The other end of the same rule. Fewer bytes left than a header is the ordinary end of
    // a journal when they are erased — and a torn header when they are not. Reporting an end
    // of history there would hand a caller an offset pointing into cells a program cycle has
    // already cleared, which on NOR cannot be written again without erasing the block.
    let align = ProgramAlign::BYTE;
    let mut journal = [ERASED_BYTE; 64];
    let written = frame::encode(
        &RecordRef::RunCompleted { result: b"r" },
        align,
        &mut journal,
    )
    .expect("room");

    // Erased short remainder: the ordinary end.
    let clean_end = written + HEADER_BYTES - 1;
    let mut clean = Scan::new(&journal[..clean_end], align);
    assert!(matches!(
        clean.next(),
        Some(Ok(RecordRef::RunCompleted { .. }))
    ));
    assert!(clean.next().is_none());
    assert_eq!(clean.offset(), written);

    // The same remainder with one programmed byte in it: a torn header.
    for at in 0..HEADER_BYTES - 1 {
        let mut torn = journal;
        torn[written + at] = 0x00;
        let mut scan = Scan::new(&torn[..clean_end], align);
        assert!(matches!(
            scan.next(),
            Some(Ok(RecordRef::RunCompleted { .. }))
        ));
        assert_eq!(
            scan.next(),
            Some(Err(DecodeError::Truncated)),
            "a programmed byte {at} into a short remainder is a torn header"
        );
        assert!(scan.next().is_none());
        assert_eq!(scan.offset(), written);
    }
}

#[test]
fn a_scan_reads_its_slice_as_the_whole_journal() {
    // `Scan`'s erased-tail rule is "an erased header *and* erased to the end", which is what
    // catches a stride mismatch — and which makes the slice a precondition rather than
    // merely a bound: bytes after the last frame that are not erased are damage as far as
    // this type is concerned. A caller with a bank header or a generation seal in the same
    // erase block passes the journal region, not the block.
    //
    // Pinned here because it is the shape rung 0.2 arrives in, and a caller that gets it
    // wrong sees a perfectly good journal reported as corrupt on every boot.
    let align = ProgramAlign::new(8).expect("a non-zero alignment");
    let mut block = [ERASED_BYTE; 256];
    let written =
        frame::encode(&RecordRef::RunCompleted { result: b"r" }, align, &mut block).expect("room");

    // Something that is not a record living at the end of the same erase block.
    block[252..256].copy_from_slice(&[0xDE, 0xAD, 0xBE, 0xEF]);

    let mut whole_block = Scan::new(&block, align);
    assert!(matches!(
        whole_block.next(),
        Some(Ok(RecordRef::RunCompleted { .. }))
    ));
    assert_eq!(
        whole_block.next(),
        Some(Err(DecodeError::IntegrityFailed)),
        "a non-erased tail is damage, which is the price of catching a stride mismatch"
    );

    // The journal region alone reads clean, which is the contract.
    let mut journal_only = Scan::new(&block[..252], align);
    assert!(matches!(
        journal_only.next(),
        Some(Ok(RecordRef::RunCompleted { .. }))
    ));
    assert!(journal_only.next().is_none());
    assert_eq!(journal_only.offset(), written);
}

#[test]
fn a_scan_at_a_larger_alignment_than_the_writer_used_is_caught_by_the_seal() {
    // The other half of the stride mismatch, which this file used to pin as *not* handled: a
    // reader striding by more than the writer used steps over whole frames and lands on
    // erased bytes, which was an ordinary end of history in every respect the scan could
    // see. Issue #24's commit seal is what closed it, and closed it by accident rather than
    // by design — which is worth writing down, because it was the one failure this module
    // documented as undetectable.
    //
    // A seal is at a fixed offset from the frame it seals: the frame body rounded up to the
    // granularity the reader believes in. A reader that believes in a larger one looks for
    // the seal past the end of the real record, and finds either erased media or another
    // record's bytes. No byte of a seal is ever erased, so the first of those is refused
    // outright; the second is a 28-bit coincidence away from being refused, which is a CRC's
    // kind of certainty rather than a proof and is stated as such.
    let writer = ProgramAlign::new(8).expect("a non-zero alignment");
    let mut journal = [ERASED_BYTE; 2_048];
    let mut at = 0;
    for index in 0..4_u32 {
        let record = RecordRef::EffectCompleted {
            seq: EffectSeq(index),
            result: b"x",
        };
        at += frame::encode(&record, writer, &mut journal[at..]).expect("room");
    }

    let mut over_striding = Scan::new(&journal, ProgramAlign::new(256).expect("non-zero"));
    assert_eq!(
        over_striding.next(),
        Some(Err(DecodeError::Unsealed)),
        "a larger stride looks for the seal past the record it belongs to"
    );
    assert_eq!(
        over_striding.offset(),
        0,
        "and reports no history rather than a short prefix of it"
    );

    // The same journal at the granularity it was written with walks every record.
    let matched: Vec<Result<RecordRef<'_>, DecodeError>> = Scan::new(&journal, writer).collect();
    assert_eq!(matched.len(), 4, "{matched:?}");
    assert!(matched.iter().all(Result::is_ok));
    assert_eq!(
        Scan::new(&journal, writer).count(),
        4,
        "the reader that agrees with the writer reaches every record, at offset {at}"
    );
}

