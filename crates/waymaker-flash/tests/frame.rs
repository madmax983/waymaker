//! The record frame, tested through the surface a storage driver sees.
//!
//! Design document §09 fixes the frame and four properties it says may not change. Each of
//! those has a test here that fails if it stops holding:
//!
//! * lengths validated against the caller's buffer *before* anything is read —
//!   [`a_truncated_frame_is_refused_at_every_length`] and
//!   [`arbitrary_bytes_are_never_a_record_and_never_panic`];
//! * unknown record kinds skippable only where the format version permits —
//!   [`an_unknown_kind_is_self_delimiting`] and [`a_scan_will_not_skip_an_unknown_kind`];
//! * padding to the device's program alignment with stale tail bytes never interpreted —
//!   [`padding_is_written_erased_and_never_read_back`] and [`a_scan_walks_padded_frames`];
//! * numeric kinds and borrowed bytes — the decoded record borrows the caller's page,
//!   which [`a_decoded_record_borrows_the_callers_page`] pins.
//!
//! Every one of the six [`RecordRef`] variants has a golden frame: two of them would
//! otherwise be pinned only by the encoder and the decoder agreeing with each other, which
//! is the one comparison a golden vector exists to avoid.
//!
//! # Why the golden frames are not built by the encoder
//!
//! Every byte array in [`golden`] was produced by a reference implementation written
//! separately from this crate, from §09's field list rather than from `frame.rs`. A golden
//! vector generated by the code under test proves only that the code agrees with itself:
//! a wrong magic, a swapped field order or a CRC over the wrong range all round-trip
//! perfectly. These arrays are the one place where the format is stated by something other
//! than the implementation, which is what makes the round-trip tests below mean anything.

use waymaker_core::{ActivityKind, DecodeError, EffectSeq, RecordKind, RecordRef};
use waymaker_flash::frame::{
    self, Decoded, ERASED_BYTE, FORMAT_VERSION, FRAME_OVERHEAD_BYTES, HEADER_BYTES, MAGIC,
    MAX_FRAME_BYTES, MAX_PAYLOAD_BYTES, ProgramAlign, Scan,
};

/// Records written out by an independent reference implementation of §09's field list.
///
/// The comment above each says what it holds, so a reader can check the bytes by hand
/// against the frame in §09 without running anything.
///
/// Each one ends in its **commit seal**, one program unit wide, which is the frame's own
/// four `frame_crc` bytes with bit 7 of each cleared, repeated to fill the unit. That is
/// checkable by eye against the four bytes immediately before the padding, which is why the
/// seal is spelled out here rather than computed: a fixture the code under test produces is
/// not a fixture.
///
/// `pub` inside a private module is unreachable from anywhere, which is what a fixture is;
/// `pub(super)` would trade this lint for `redundant_pub_crate`, so the allow is here
/// rather than the module reshaped to suit a lint pair that cannot both be satisfied.
#[allow(
    unreachable_pub,
    reason = "a test-only table of golden bytes is reachable from its tests"
)]
mod golden {
    /// `RunStarted { workflow_kind: 0xBEEF, workflow_version: 7, input: b"hi" }`,
    /// alignment 1. Payload is `EF BE 07 00 68 69`.
    pub const RUN_STARTED: [u8; 23] = [
        0x57, 0x4D, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x06, 0x00, 0xB1, 0x4F, 0xEF, 0xBE, 0x07,
        0x00, 0x68, 0x69, 0xE8, 0xD9, 0x09, 0xA3, //
        0x68, // commit seal: 0xE8 & 0x7F
    ];

    /// `EffectScheduled { seq: 0x0102_0304, kind: 0x1234, input_len: 0x40,
    /// input_crc: 0xDEAD_BEEF }`, alignment 1. The body is exactly eight bytes.
    pub const EFFECT_SCHEDULED: [u8; 25] = [
        0x57, 0x4D, 0x01, 0x02, 0x04, 0x03, 0x02, 0x01, 0x08, 0x00, 0x17, 0x86, 0x34, 0x12, 0x40,
        0x00, 0xEF, 0xBE, 0xAD, 0xDE, 0x6F, 0xA7, 0xE7, 0x90, //
        0x6F, // commit seal: 0x6F & 0x7F
    ];

    /// `EffectCompleted { seq: 9, result: [1, 2, 3] }` at alignment 8: nineteen bytes of
    /// frame, five bytes of erased padding, and eight bytes of commit seal — the pattern
    /// twice, because a seal fills its whole program unit.
    pub const EFFECT_COMPLETED_ALIGNED: [u8; 32] = [
        0x57, 0x4D, 0x01, 0x03, 0x09, 0x00, 0x00, 0x00, 0x03, 0x00, 0x45, 0x98, 0x01, 0x02, 0x03,
        0x75, 0x07, 0xBF, 0x96, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, //
        0x75, 0x07, 0x3F, 0x16, 0x75, 0x07, 0x3F, 0x16, // commit seal: 75 07 BF 96 masked
    ];

    /// `EffectFailed { seq: 0xFFFF_FFFE, error: [0x00, 0xFF, 0x80] }` at alignment 2:
    /// nineteen bytes of frame and one byte of erased padding. A sequence near the ceiling
    /// and a payload of the two byte values a flash page can hold on its own.
    pub const EFFECT_FAILED: [u8; 22] = [
        0x57, 0x4D, 0x01, 0x04, 0xFE, 0xFF, 0xFF, 0xFF, 0x03, 0x00, 0x93, 0x06, 0x00, 0xFF, 0x80,
        0x9F, 0x7A, 0xD7, 0x43, 0xFF, //
        0x1F, 0x7A, // commit seal: the first two of 9F 7A D7 43 masked
    ];

    /// `RunFailed { error: b"why" }`, alignment 1.
    pub const RUN_FAILED: [u8; 20] = [
        0x57, 0x4D, 0x01, 0x08, 0x00, 0x00, 0x00, 0x00, 0x03, 0x00, 0x88, 0x9B, 0x77, 0x68, 0x79,
        0x97, 0x11, 0xEE, 0xE0, //
        0x17, // commit seal: 0x97 & 0x7F
    ];

    /// `RunCompleted { result: &[] }`, alignment 1: the shortest record there is.
    pub const RUN_COMPLETED_EMPTY: [u8; 17] = [
        0x57, 0x4D, 0x01, 0x07, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x32, 0x44, 0x0B, 0xF6, 0x88,
        0x39, //
        0x0B, // commit seal: 0x0B & 0x7F
    ];
}

/// A deterministic generator, so a failure can be reproduced from the seed it names.
///
/// xorshift64, which is not a good random number generator and does not need to be: the
/// tests below want a stream of values that visits payload lengths, record kinds and byte
/// positions a hand-written list would not think of, on a workspace whose layers may not
/// take a dependency of any kind — `proptest` is not available here and would be a
/// dependency-direction violation if it were reached for.
struct Rng(u64);

impl Rng {
    /// Seeded so that zero, the one state xorshift cannot leave, is unreachable.
    const fn new(seed: u64) -> Self {
        Self(seed | 1)
    }

    const fn next_u64(&mut self) -> u64 {
        let mut state = self.0;
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        self.0 = state;
        state
    }

    fn next_u8(&mut self) -> u8 {
        u8::try_from(self.next_u64() & 0xFF).unwrap_or(0)
    }

    /// A value in `0..bound`, or zero when `bound` is zero.
    ///
    /// Modulo bias is irrelevant here and a rejection loop would be a helper that can spin.
    fn below(&mut self, bound: usize) -> usize {
        if bound == 0 {
            return 0;
        }
        let drawn = self.next_u64();
        usize::try_from(drawn % (bound as u64)).unwrap_or(0)
    }
}

/// The alignments a test sweeps: one that pads nothing, the program sizes real internal
/// flash reports, and two page sizes. The larger granularities a page-programmed device
/// reports get their own test, because a sweep at 32 768 would need a 64 KiB page here.
const ALIGNMENTS: [u16; 7] = [1, 2, 4, 8, 16, 256, 512];

/// Enough room for the longest frame any test below builds, padded to the largest
/// granularity in [`ALIGNMENTS`].
const SCRATCH: usize = 2_048;

/// How many `RecordRef` variants [`sample_record`] can draw.
///
/// Proven equal to the number of variants there are by
/// [`the_sweep_draws_every_record_variant`], which maps each through an exhaustive `match`.
const SAMPLED_VARIANTS: usize = 6;

/// Builds one of the six records from a generator and a borrowed payload.
///
/// Returns the record and nothing else: every assertion belongs in a `#[test]`, because
/// `clippy.toml` exempts test *bodies* from the workspace's `unwrap`, `panic` and
/// `indexing_slicing` denials and does not exempt a helper in an integration test.
fn sample_record<'a>(rng: &mut Rng, payload: &'a [u8]) -> RecordRef<'a> {
    // `SAMPLED_VARIANTS` is the count this dispatch covers, and
    // `the_sweep_draws_every_record_variant` proves by exhaustive `match` that it is every
    // variant there is. A bare `rng.below(6)` beside a hand-written match would silently
    // stop drawing a seventh variant the day one is added — the sweep would keep passing,
    // over five sixths of the enum.
    match rng.below(SAMPLED_VARIANTS) {
        0 => RecordRef::RunStarted {
            workflow_kind: u16::try_from(rng.below(0x1_0000)).unwrap_or(0),
            workflow_version: u16::try_from(rng.below(0x1_0000)).unwrap_or(0),
            input: payload,
        },
        1 => RecordRef::EffectScheduled {
            seq: EffectSeq(u32::try_from(rng.next_u64() >> 32).unwrap_or(0)),
            kind: ActivityKind(u16::try_from(rng.below(0x1_0000)).unwrap_or(0)),
            input_len: u16::try_from(payload.len()).unwrap_or(u16::MAX),
            input_crc: u32::try_from(rng.next_u64() >> 32).unwrap_or(0),
        },
        2 => RecordRef::EffectCompleted {
            seq: EffectSeq(u32::try_from(rng.next_u64() >> 32).unwrap_or(0)),
            result: payload,
        },
        3 => RecordRef::EffectFailed {
            seq: EffectSeq(u32::try_from(rng.next_u64() >> 32).unwrap_or(0)),
            error: payload,
        },
        4 => RecordRef::RunCompleted { result: payload },
        _ => RecordRef::RunFailed { error: payload },
    }
}

/// The record a frame decoded to, or `None` for anything else.
///
/// Total: a malformed frame, an unknown kind and a short buffer all come back as `None`,
/// so a caller in a `#[test]` can assert on the shape rather than on an error type it did
/// not ask about.
fn decoded_record(bytes: &[u8]) -> Option<RecordRef<'_>> {
    match frame::decode(bytes) {
        Ok(frame::Frame {
            decoded: Decoded::Record(record),
            ..
        }) => Some(record),
        _ => None,
    }
}

#[test]
fn the_frame_constants_are_the_ones_section_09_states() {
    // Every one of these is on media for the life of a device, so each is compared with a
    // literal rather than with the constant that defines it.
    assert_eq!(
        MAGIC, 0x4D57,
        "magic reads as b\"WM\" on media, low byte first"
    );
    assert_eq!(FORMAT_VERSION, 1);
    assert_eq!(HEADER_BYTES, 12);
    assert_eq!(FRAME_OVERHEAD_BYTES, 16);
    assert_eq!(MAX_PAYLOAD_BYTES, 65_535);
    assert_eq!(ERASED_BYTE, 0xFF);
    assert_eq!(MAGIC.to_le_bytes(), *b"WM");
}

#[test]
fn the_encoder_writes_the_golden_frames_byte_for_byte() {
    // The one test that can catch a wrong constant, a swapped field or a checksum over the
    // wrong range: the expected bytes came from a reference implementation written from
    // §09 rather than from this crate.
    let cases: [(RecordRef<'_>, u16, &[u8]); 6] = [
        (
            RecordRef::RunStarted {
                workflow_kind: 0xBEEF,
                workflow_version: 7,
                input: b"hi",
            },
            1,
            &golden::RUN_STARTED,
        ),
        (
            RecordRef::EffectScheduled {
                seq: EffectSeq(0x0102_0304),
                kind: ActivityKind(0x1234),
                input_len: 0x40,
                input_crc: 0xDEAD_BEEF,
            },
            1,
            &golden::EFFECT_SCHEDULED,
        ),
        (
            RecordRef::EffectCompleted {
                seq: EffectSeq(9),
                result: &[1, 2, 3],
            },
            8,
            &golden::EFFECT_COMPLETED_ALIGNED,
        ),
        (
            RecordRef::EffectFailed {
                seq: EffectSeq(0xFFFF_FFFE),
                error: &[0x00, 0xFF, 0x80],
            },
            2,
            &golden::EFFECT_FAILED,
        ),
        (
            RecordRef::RunFailed { error: b"why" },
            1,
            &golden::RUN_FAILED,
        ),
        (
            RecordRef::RunCompleted { result: &[] },
            1,
            &golden::RUN_COMPLETED_EMPTY,
        ),
    ];

    for (record, alignment, expected) in cases {
        let align = ProgramAlign::new(alignment).expect("a non-zero alignment");
        let mut page = [0_u8; SCRATCH];
        let written = frame::encode(&record, align, &mut page).expect("room for the frame");

        assert_eq!(written, expected.len(), "{record:?}");
        assert_eq!(&page[..written], expected, "{record:?}");
        assert_eq!(
            frame::encoded_len(&record, align),
            Ok(written),
            "the reserved length and the written length must agree for {record:?}"
        );
    }
}

#[test]
fn the_golden_frames_decode_to_the_records_they_were_built_from() {
    // The other direction, against the same externally produced bytes: an encoder and a
    // decoder that agree with each other but not with §09 pass a round-trip test and fail
    // this one.
    assert_eq!(
        decoded_record(&golden::RUN_STARTED),
        Some(RecordRef::RunStarted {
            workflow_kind: 0xBEEF,
            workflow_version: 7,
            input: b"hi",
        })
    );
    assert_eq!(
        decoded_record(&golden::EFFECT_SCHEDULED),
        Some(RecordRef::EffectScheduled {
            seq: EffectSeq(0x0102_0304),
            kind: ActivityKind(0x1234),
            input_len: 0x40,
            input_crc: 0xDEAD_BEEF,
        })
    );
    assert_eq!(
        decoded_record(&golden::EFFECT_COMPLETED_ALIGNED),
        Some(RecordRef::EffectCompleted {
            seq: EffectSeq(9),
            result: &[1, 2, 3],
        })
    );
    assert_eq!(
        decoded_record(&golden::EFFECT_FAILED),
        Some(RecordRef::EffectFailed {
            seq: EffectSeq(0xFFFF_FFFE),
            error: &[0x00, 0xFF, 0x80],
        })
    );
    assert_eq!(
        decoded_record(&golden::RUN_FAILED),
        Some(RecordRef::RunFailed { error: b"why" })
    );
    assert_eq!(
        decoded_record(&golden::RUN_COMPLETED_EMPTY),
        Some(RecordRef::RunCompleted { result: &[] })
    );
}

#[test]
fn the_sweep_draws_every_record_variant() {
    // The exhaustive `match` is the whole test: a variant added to `RecordRef` is a compile
    // error here, and the only index it can be given is one `sample_record` does not
    // dispatch. Without this, the round-trip sweep below would keep passing while quietly
    // covering a shrinking fraction of the enum.
    const fn index_of(record: &RecordRef<'_>) -> usize {
        match record {
            RecordRef::RunStarted { .. } => 0,
            RecordRef::EffectScheduled { .. } => 1,
            RecordRef::EffectCompleted { .. } => 2,
            RecordRef::EffectFailed { .. } => 3,
            RecordRef::RunCompleted { .. } => 4,
            RecordRef::RunFailed { .. } => 5,
        }
    }

    let mut rng = Rng::new(0x5EED_0006);
    let mut drawn = [false; SAMPLED_VARIANTS];
    for _ in 0..1_000 {
        let record = sample_record(&mut rng, b"payload");
        let index = index_of(&record);
        assert!(
            index < SAMPLED_VARIANTS,
            "{record:?} is outside the dispatch"
        );
        drawn[index] = true;
    }
    assert!(
        drawn.iter().all(|seen| *seen),
        "the generator never drew {:?}",
        drawn
            .iter()
            .enumerate()
            .filter(|(_, seen)| !**seen)
            .map(|(index, _)| index)
            .collect::<Vec<usize>>()
    );
}

#[test]
fn every_record_round_trips_at_every_alignment() {
    // The property the issue asks for, over random records and random payload lengths.
    // Zero and one are drawn explicitly rather than left to chance: they are the lengths
    // an off-by-one lives at, and a uniform draw over a few hundred visits them rarely.
    let mut rng = Rng::new(0x5EED_0001);
    let mut page = [0_u8; SCRATCH];
    let mut payload = [0_u8; 512];
    let mut seen_empty = false;
    let mut seen_long = false;

    for iteration in 0..4_000_u32 {
        let length = match iteration % 8 {
            0 => 0,
            1 => 1,
            2 => payload.len(),
            _ => rng.below(payload.len() + 1),
        };
        for slot in payload.iter_mut().take(length) {
            *slot = rng.next_u8();
        }
        let alignment = ALIGNMENTS[rng.below(ALIGNMENTS.len())];
        let align = ProgramAlign::new(alignment).expect("a non-zero alignment");

        let record = sample_record(&mut rng, &payload[..length]);
        seen_empty |= length == 0;
        seen_long |= length == payload.len();

        let written = frame::encode(&record, align, &mut page)
            .unwrap_or_else(|error| panic!("iteration {iteration}: {error}"));
        assert_eq!(written % usize::from(alignment), 0, "iteration {iteration}");
        assert_eq!(
            frame::encoded_len(&record, align),
            Ok(written),
            "iteration {iteration}"
        );

        let decoded = frame::decode(&page[..written])
            .unwrap_or_else(|error| panic!("iteration {iteration}: {error}"));
        assert_eq!(
            decoded.decoded,
            Decoded::Record(record),
            "iteration {iteration}"
        );
        // The frame's own length excludes the padding, which is what makes the format
        // self-delimiting independently of the device it was written on.
        assert_eq!(
            decoded.frame_len,
            FRAME_OVERHEAD_BYTES + payload_len_of(&record),
            "iteration {iteration}"
        );
        assert!(decoded.frame_len <= written, "iteration {iteration}");
    }

    assert!(
        seen_empty && seen_long,
        "the sweep skipped a boundary length"
    );
}

/// The payload length §09's `payload_len` field holds for `record`.
///
/// Written out here rather than read back from the encoder: a test that asked the code
/// under test how long its own payload is would agree with any answer.
const fn payload_len_of(record: &RecordRef<'_>) -> usize {
    match record {
        RecordRef::RunStarted { input, .. } => 4 + input.len(),
        RecordRef::EffectScheduled { .. } => 8,
        RecordRef::EffectCompleted { result, .. } | RecordRef::RunCompleted { result } => {
            result.len()
        }
        RecordRef::EffectFailed { error, .. } | RecordRef::RunFailed { error } => error.len(),
    }
}

#[test]
fn a_decoded_record_borrows_the_callers_page() {
    // "Borrowed bytes": the decoder hands back a window into the buffer the caller read
    // the page into, not a copy. A decoder that copied would need somewhere to copy to,
    // and this crate has no allocator.
    let mut page = [0_u8; SCRATCH];
    let written = frame::encode(
        &RecordRef::EffectCompleted {
            seq: EffectSeq(4),
            result: b"payload",
        },
        ProgramAlign::BYTE,
        &mut page,
    )
    .expect("room for the frame");

    let Some(RecordRef::EffectCompleted { result, .. }) = decoded_record(&page[..written]) else {
        panic!("the frame holds a completion")
    };
    let offset = HEADER_BYTES;
    assert_eq!(result.as_ptr(), page[offset..].as_ptr());
}

#[test]
fn encode_refuses_an_output_buffer_one_byte_short() {
    // Validated against the caller's buffer before anything is written. One byte short
    // rather than obviously short: a check written as `>` instead of `>=` passes the
    // obvious case.
    let record = RecordRef::RunFailed { error: b"nope" };
    let align = ProgramAlign::new(4).expect("a non-zero alignment");
    let needed = frame::encoded_len(&record, align).expect("an encodable record");

    let mut exact = [0_u8; SCRATCH];
    assert_eq!(
        frame::encode(&record, align, &mut exact[..needed]),
        Ok(needed)
    );

    let mut short = [0_u8; SCRATCH];
    assert_eq!(
        frame::encode(&record, align, &mut short[..needed - 1]),
        Err(DecodeError::LengthOutOfBounds)
    );
    // Nothing was written: a partial frame in a staging buffer is a frame a later flush
    // could program.
    assert!(short.iter().all(|byte| *byte == 0));
}

#[test]
fn encode_refuses_a_payload_the_length_field_cannot_describe() {
    // `payload_len` is a `u16`, so a longer payload has no frame. Refused rather than
    // truncated: a silently shortened record is a record whose bytes are not the ones the
    // workflow returned.
    let oversized = vec![0_u8; MAX_PAYLOAD_BYTES + 1];
    let record = RecordRef::RunCompleted { result: &oversized };
    assert_eq!(
        frame::encoded_len(&record, ProgramAlign::BYTE),
        Err(DecodeError::LengthOutOfBounds)
    );

    // `RunStarted` spends four of those bytes on the workflow identity, so its input
    // ceiling is four lower — the boundary a payload-length check that forgot the header
    // would get wrong.
    let at_limit = vec![0_u8; MAX_PAYLOAD_BYTES - 4];
    assert!(
        frame::encoded_len(
            &RecordRef::RunStarted {
                workflow_kind: 1,
                workflow_version: 1,
                input: &at_limit,
            },
            ProgramAlign::BYTE,
        )
        .is_ok()
    );
    let over_limit = vec![0_u8; MAX_PAYLOAD_BYTES - 3];
    assert_eq!(
        frame::encoded_len(
            &RecordRef::RunStarted {
                workflow_kind: 1,
                workflow_version: 1,
                input: &over_limit,
            },
            ProgramAlign::BYTE,
        ),
        Err(DecodeError::LengthOutOfBounds)
    );
}

#[test]
fn the_longest_frame_round_trips() {
    // The other end of the range from the empty payload: a `payload_len` of `u16::MAX`,
    // where an arithmetic that widened too late would fold back on itself.
    let payload = vec![0xA5_u8; MAX_PAYLOAD_BYTES];
    let record = RecordRef::RunCompleted { result: &payload };
    let align = ProgramAlign::new(256).expect("a non-zero alignment");
    let needed = frame::encoded_len(&record, align).expect("an encodable record");
    let mut page = vec![0_u8; needed];

    assert_eq!(frame::encode(&record, align, &mut page), Ok(needed));
    assert_eq!(decoded_record(&page), Some(record));
}

#[test]
fn a_truncated_frame_is_refused_at_every_length() {
    // "All lengths are validated against caller buffers before reading." Every prefix, not
    // a sample: a bounds check that only covers inputs shorter than the header leaves the
    // payload and the trailer unguarded, and that is exactly the shape of the bug this
    // sweep exists to find.
    for alignment in ALIGNMENTS {
        let align = ProgramAlign::new(alignment).expect("a non-zero alignment");
        let mut page = [0_u8; SCRATCH];
        let written = frame::encode(
            &RecordRef::EffectFailed {
                seq: EffectSeq(2),
                error: b"a longer payload, so the sweep has something to walk through",
            },
            align,
            &mut page,
        )
        .expect("room for the frame");
        let frame_len = FRAME_OVERHEAD_BYTES + 60;

        for length in 0..frame_len {
            assert!(
                frame::decode(&page[..length]).is_err(),
                "alignment {alignment}: a {length}-byte prefix decoded"
            );
        }
        // A frame is complete at `frame_len`, before its padding: the padding belongs to
        // the device rather than to the frame, so a reader must not need it to decode.
        assert!(frame::decode(&page[..frame_len]).is_ok(), "{alignment}");
        assert!(frame::decode(&page[..written]).is_ok(), "{alignment}");
    }
}

#[test]
fn a_single_bit_flip_anywhere_in_a_frame_is_refused() {
    // What the two checksums are for. Swept over every bit of the frame rather than
    // sampled: a checksum computed over the wrong range shows up as some region where a
    // flip changes nothing, and a sample can miss the region.
    //
    // The assertion is `is_none()`, not "not the record we started with". Every byte of a
    // frame is inside `crc16(0..10)`, or is the header checksum, or is inside
    // `crc32(0..12+N)`, or is the frame checksum — so a flip anywhere must be *refused*,
    // and nothing weaker is the property. Asserting only that the result differs from the
    // original would pass for a flip in a payload byte that changed the record into a
    // different, happily-decoded one, which is exactly a decoder with no payload checksum.
    //
    // Swept at every alignment, because the padded frame is a different code path in the
    // encoder and a test that only ever ran at alignment one would never enter it.
    for alignment in ALIGNMENTS {
        let align = ProgramAlign::new(alignment).expect("a non-zero alignment");
        let mut page = [0_u8; SCRATCH];
        let record = RecordRef::EffectCompleted {
            seq: EffectSeq(0x1234_5678),
            result: b"twenty-nine bytes of payload!",
        };
        let written = frame::encode(&record, align, &mut page).expect("room");
        let frame_len = FRAME_OVERHEAD_BYTES + 29;

        for index in 0..frame_len {
            for bit in 0..8 {
                let mut damaged = page;
                damaged[index] ^= 1 << bit;
                assert!(
                    decoded_record(&damaged[..written]).is_none(),
                    "alignment {alignment}, byte {index} bit {bit} still decoded"
                );
            }
        }

        // The pad is the complement of that claim: a flip there changes nothing, because
        // nothing reads it.
        for index in frame_len..written {
            for bit in 0..8 {
                let mut stale = page;
                stale[index] ^= 1 << bit;
                assert_eq!(
                    decoded_record(&stale[..written]),
                    Some(record),
                    "alignment {alignment}, pad byte {index} bit {bit} was interpreted"
                );
            }
        }
    }
}

#[test]
fn arbitrary_bytes_are_never_a_record_and_never_panic() {
    // The bounded-decoding guarantee, from the outside. `#![forbid(unsafe_code)]` and the
    // workspace's denial of `indexing_slicing` mean an out-of-bounds *read* is not
    // expressible here; what is expressible is a panic, and on this target
    // `panic = "abort"` makes a panic a bricked device. So the property under test is that
    // the decoder returns.
    let mut rng = Rng::new(0x5EED_0002);
    let mut buffer = [0_u8; 128];

    for _ in 0..20_000 {
        let length = rng.below(buffer.len() + 1);
        for slot in buffer.iter_mut().take(length) {
            *slot = rng.next_u8();
        }
        // Random bytes almost never carry the magic, so this sweep on its own would test
        // the first check and nothing else. `mutating_a_valid_frame_reaches_every_refusal`
        // is what walks the deep paths; this one is here for the shallow ones and for
        // lengths a valid frame never has.
        assert!(decoded_record(&buffer[..length]).is_none());
    }
}

#[test]
fn damaging_a_frame_without_resealing_it_is_always_caught() {
    // The honest half of the fuzz for the checksums. Starting from a frame that decodes
    // and damaging a few bytes puts the generator *inside* the decoder rather than at its
    // front door — random buffers hardly ever carry the magic, so a blind sweep tests the
    // first check and nothing else.
    //
    // Nothing here reseals, so every edit is a corruption the two checksums exist to
    // catch, and the property is that not one of thirty thousand gets through.
    let mut rng = Rng::new(0x5EED_0003);
    let mut page = [0_u8; SCRATCH];
    frame::encode(
        &RecordRef::EffectScheduled {
            seq: EffectSeq(7),
            kind: ActivityKind(3),
            input_len: 16,
            input_crc: 0x0BAD_F00D,
        },
        ProgramAlign::BYTE,
        &mut page,
    )
    .expect("room for the frame");

    // The decoder's business is the frame, and the commit seal is not part of it: a record
    // whose seal alone was flipped decodes perfectly, which is `Scan`'s finding rather than
    // `decode`'s. So the damage lands in the body, and `tests/commit.rs` is where a damaged
    // seal is swept.
    let body = frame::body_len(
        &RecordRef::EffectScheduled {
            seq: EffectSeq(7),
            kind: ActivityKind(3),
            input_len: 16,
            input_crc: 0x0BAD_F00D,
        },
        ProgramAlign::BYTE,
    )
    .expect("this record encodes");

    let mut integrity = 0_u32;
    let mut truncated = 0_u32;

    for _ in 0..30_000 {
        let mut damaged = page;
        let edits = 1 + rng.below(3);
        for _ in 0..edits {
            let at = rng.below(body);
            damaged[at] ^= 1 << rng.below(8);
        }
        // A flip is its own inverse, so two edits at the same bit leave the frame
        // pristine — and a pristine frame decoding is not a finding. Discarded here rather
        // than avoided in the generator, because the generator that avoided it would be
        // the thing under test.
        if damaged[..body] == page[..body] {
            continue;
        }
        let length = if rng.below(4) == 0 {
            rng.below(body + 1)
        } else {
            body
        };

        match frame::decode(&damaged[..length]) {
            // A damaged frame that still decodes is a checksum collision. Against a
            // 32-bit checksum over thirty thousand draws, the expected count is a small
            // fraction of one.
            Ok(frame) => panic!("a damaged frame decoded as {frame:?}"),
            Err(DecodeError::IntegrityFailed) => integrity += 1,
            Err(DecodeError::Truncated) => truncated += 1,
            Err(other) => panic!("an unresealed frame reached {other}"),
        }
    }

    assert!(integrity > 0, "no frame failed a checksum");
    assert!(truncated > 0, "no frame was cut short");
}

#[test]
fn resealing_a_damaged_frame_reaches_every_check_past_the_checksums() {
    // The other half, and the one that matters for coverage. A checksum is doing its job
    // when it rejects a random edit — which is exactly why a sweep that does not reseal
    // can never reach the version check, the kind check or the body checks: those are all
    // behind two checksums that a random edit will not satisfy.
    //
    // So this sweep damages a byte and then recomputes both checksums, the way a wrong
    // encoder or a hostile writer would. What it produces is a frame that is *internally
    // consistent* and still not a record this firmware may accept, and the counters at the
    // end are what prove the generator got that far rather than being turned away at the
    // door.
    let mut rng = Rng::new(0x5EED_0005);
    let mut page = [0_u8; SCRATCH];
    let clean = frame::encode(
        &RecordRef::EffectScheduled {
            seq: EffectSeq(7),
            kind: ActivityKind(3),
            input_len: 16,
            input_crc: 0x0BAD_F00D,
        },
        ProgramAlign::BYTE,
        &mut page,
    )
    .expect("room for the frame");

    let mut integrity = 0_u32;
    let mut unsupported_version = 0_u32;
    let mut unknown_kind = 0_u32;
    let mut malformed = 0_u32;
    let mut truncated = 0_u32;
    let mut accepted = 0_u32;

    for _ in 0..30_000 {
        let mut damaged = page;
        let edits = 1 + rng.below(3);
        for _ in 0..edits {
            let at = rng.below(clean);
            damaged[at] = rng.next_u8();
        }
        reseal(&mut damaged[..clean], ProgramAlign::BYTE);
        let length = if rng.below(4) == 0 {
            rng.below(clean + 1)
        } else {
            clean
        };

        match frame::decode(&damaged[..length]) {
            Ok(frame::Frame {
                decoded: Decoded::Record(_),
                ..
            }) => accepted += 1,
            Ok(frame::Frame {
                decoded: Decoded::UnknownKind(_),
                ..
            }) => unknown_kind += 1,
            Err(DecodeError::IntegrityFailed) => integrity += 1,
            Err(DecodeError::UnsupportedFormatVersion) => unsupported_version += 1,
            Err(DecodeError::MalformedRecord) => malformed += 1,
            Err(DecodeError::Truncated) => truncated += 1,
            Err(
                DecodeError::LengthOutOfBounds
                | DecodeError::UnknownRecordKind
                | DecodeError::Unsealed,
            ) => {
                panic!("decode returned an error it documents that it never returns")
            }
        }
    }

    // Every one of these is a distinct decision the decoder takes after both checksums
    // have held. A zero would mean the sweep never exercised it, which is what makes an
    // impressive-looking fuzz test decorative.
    assert!(
        integrity > 0,
        "the magic was never damaged; resealing does not repair it"
    );
    assert!(truncated > 0, "no resealed frame was cut short");
    assert!(
        unsupported_version > 0,
        "the version byte was never damaged into an unsupported one"
    );
    assert!(unknown_kind > 0, "the kind byte was never damaged");
    assert!(
        malformed > 0,
        "no frame reached the body checks with a body that did not fit its kind"
    );
    assert!(
        accepted > 0,
        "no resealed frame decoded, so the sweep never got past the checksums at all"
    );
}

