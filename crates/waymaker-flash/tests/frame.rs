/// Recomputes both checksums and the commit seal over a record whose fields a test edited.
///
/// Without this, every edit below would be rejected as a checksum failure before it
/// reached the check it was written to exercise — which would make each of those tests
/// pass for the wrong reason. Since issue #24 that includes the commit seal: a record whose
/// frame check moved and whose seal did not is refused as unsealed, one stop condition
/// earlier than the one the edit was aimed at.
///
/// `align` is the granularity the record was encoded at, and it is a parameter rather than
/// a guess because nothing in a slice of bytes says where the body stops and the seal
/// starts.
fn reseal(frame_bytes: &mut [u8], align: ProgramAlign) {
    let header_crc = crc16(frame_bytes.get(..HEADER_BYTES - 2).unwrap_or_default());
    for (slot, byte) in frame_bytes
        .iter_mut()
        .skip(HEADER_BYTES - 2)
        .zip(header_crc.to_le_bytes())
    {
        *slot = byte;
    }

    // The covered range comes from the `payload_len` in the header, never from the length
    // of the slice handed in. Deriving it from the slice would be right only when there is
    // no padding, so the first tamper test written at an alignment above one would reseal
    // over the pad and pass for the wrong reason — and it would look like it was testing
    // the padded path.
    let payload_len = frame_bytes
        .get(HEADER_BYTES - 4..HEADER_BYTES - 2)
        .and_then(|slice| <[u8; 2]>::try_from(slice).ok())
        .map_or(0, |bytes| usize::from(u16::from_le_bytes(bytes)));
    let covered = HEADER_BYTES.saturating_add(payload_len);
    let frame_crc = crc32(frame_bytes.get(..covered).unwrap_or_default());
    for (slot, byte) in frame_bytes
        .iter_mut()
        .skip(covered)
        .zip(frame_crc.to_le_bytes())
    {
        *slot = byte;
    }

    // And the seal that says the record was committed, over the check just written. Skipped
    // when the caller handed in the frame alone: a test that only decodes has no seal in its
    // slice, and inventing one past the end is not this helper's business.
    let frame_len = covered.saturating_add(waymaker_flash::frame::FRAME_CRC_BYTES);
    let Some(body) = align.round_up(frame_len) else {
        return;
    };
    let pattern = frame::commit_seal(frame_crc);
    for (at, slot) in frame_bytes.iter_mut().skip(body).enumerate() {
        if let Some(byte) = pattern.get(at % 4) {
            *slot = *byte;
        }
    }
}

/// CRC-16/CCITT-FALSE, written out again here on purpose.
///
/// The crate's own implementation is private, and a test that reached for it would be
/// resealing an edited frame with the very code the frame's checksums are supposed to be
/// an independent check on. Anchored to the catalogue by
/// [`the_tests_own_checksums_reproduce_the_published_check_values`]: a second copy of one
/// wrong polynomial agrees with the first perfectly, and every golden vector, round trip
/// and tamper test built on the pair would be consistent with nothing outside this
/// repository.
fn crc16(bytes: &[u8]) -> u16 {
    let mut crc: u16 = 0xFFFF;
    for byte in bytes {
        crc ^= u16::from(*byte) << 8;
        for _ in 0..8 {
            crc = if crc & 0x8000 == 0 {
                crc << 1
            } else {
                (crc << 1) ^ 0x1021
            };
        }
    }
    crc
}

/// CRC-32/ISO-HDLC, written out again here for the same reason as [`crc16`].
fn crc32(bytes: &[u8]) -> u32 {
    let mut crc: u32 = 0xFFFF_FFFF;
    for byte in bytes {
        crc ^= u32::from(*byte);
        for _ in 0..8 {
            crc = if crc & 1 == 0 {
                crc >> 1
            } else {
                (crc >> 1) ^ 0xEDB8_8320
            };
        }
    }
    crc ^ 0xFFFF_FFFF
}

#[test]
fn the_tests_own_checksums_reproduce_the_published_check_values() {
    // This file carries its own `crc16` and `crc32` so that `reseal` does not edit a frame
    // with the code under test. A second implementation needs an anchor of its own, or it
    // is just a second chance to make the same mistake — these are the values every
    // specification of these two algorithms states for `b"123456789"`.
    assert_eq!(crc16(b"123456789"), 0x29B1, "CRC-16/CCITT-FALSE");
    assert_eq!(crc32(b"123456789"), 0xCBF4_3926, "CRC-32/ISO-HDLC");
}

#[test]
